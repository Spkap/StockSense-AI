-- Private per-user research, independent from the shared guest cache.
CREATE TABLE public.user_analysis_cache (
  LIKE public.analysis_cache INCLUDING DEFAULTS,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  PRIMARY KEY (user_id, ticker)
);
ALTER TABLE public.user_analysis_cache ALTER COLUMN id DROP DEFAULT;
ALTER TABLE public.user_analysis_cache ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE public.user_analysis_cache ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.user_analysis_cache FROM PUBLIC, anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.user_analysis_cache TO authenticated;
CREATE POLICY "Users manage own research" ON public.user_analysis_cache
  FOR ALL TO authenticated USING ((SELECT auth.uid()) = user_id)
  WITH CHECK ((SELECT auth.uid()) = user_id);
CREATE INDEX user_analysis_cache_recent ON public.user_analysis_cache (user_id, created_at DESC);
